from typing import Any, Dict, List, Tuple


@dataclass(frozen=True)
class DBFFieldDef:
    name: str  # Max 10 ASCII chars
    ftype: str  # 'C', 'N', 'D', 'L'
    length: int
    decimals: int = 0
    required: bool = False
    default: Any = None


@dataclass(frozen=True)
class DBFTableSchema:
    name: str
    fields: Tuple[DBFFieldDef, ...]
    indexed_fields: Tuple[str, ...] = field(default_factory=tuple)
    unique_fields: Tuple[str, ...] = field(default_factory=tuple)

    @property
    def header_length(self) -> int:
        return 32 + (32 * len(self.fields)) + 1

    @property
    def record_length(self) -> int:
        return 1 + sum(f.length for f in self.fields)


